using System;
using System.Collections.Generic;
using System.Text;

namespace C_Sharp_P58.Types
{
    public class Classes
    {
        private   int x;  // це поле з доступом тільки в межах класу
        protected int y;  // це поле доступне також у спадкових класах
        public    int w;  // це поле доступне з усіх класів (для полів - не рекомендується)

        // Properties - Властивості. Конструкції, що формують аксесори автоматично або спрощено
        public int X { get; set; }   // Регістрозалежність (case sensitivity) - різне
                                     // сприйняття символів різного розміру. (не рекомендується
                                     // створення елементів, імена яких відрізняються лише
                                     // регістром символів: x та Х) Спосіб вирішення - додавання 
                                     // "_" до імен приватних елементів
                                     // 
        private int _y;              // Не авто-властивість: вводиться прихована змінна
        public int Y {               // та прямо описуються аксесори: геттер та сеттер
            get => _y;               // В таких формах можна, наприклад, додати перевірку
            set {                    // або додаткову обробку даних.
                _y = value;          // Поширена практика - формування повідомлень про зміни
                Console.WriteLine($"Зафіксована зміна Y = {value}");
            }                        // 
        }                            // 
        // Властивості з різними аксесорами:
        public int A { get; private set; }  // читання - для всіх, а зміна - тільки в класі
        public int B { get => 10; }  // тільки для читання - як замінник констант
        public int C { get; init; }  // читання + ініціалізація (у конструкторі)
        public String TypeName { get => this.GetType().Name;  }

        // Конструктори: може бути декілька з різними модифікаторами доступу
        public Classes()  // конструктор без параметрів
        {
            A = 10;
        }
        public Classes(int a)  // конструктор з параметрами
        {
            A = a;
        }
        private Classes(int a, int c)  // приватний конструктор
        {
            A = a;
            C = c;
        }
        // Аналогічно до С++ описання будь-якого конструктора прибирає 
        // конструктор за замовчанням


        public void Demo()  // метод, доступний з усіх класів (для методів - ОК)
        {
            Console.WriteLine("Типи даних. Класи.");
            Y = 10;   // виклик set{} з передачею value = 10
            Console.WriteLine(Y);  // викликається get і його результат виводиться
            Console.WriteLine("Type of object: " + TypeName);
        }

        class SubClass   // Nested type (nested class) - внутрішній тип (в середині іншого)
        {
            public int Sub { get; set; }
        }
    }
}
/* Типи даних. Класи.
 * Типи даних у С# (.NET) - це об'єкти, які формуються (набираються) із 
 * заданого переліку "будівельних блоків". Їх перелік та особливості
 * використання регулюються положенням CTS (Common Type System):
 * - є декілька модифікаторів видності: для типів та їх частин
 *    public, private - для всіх 
 *    internal - для типів, 
 *    protected - для елементів
 * - "будівельними блоками" є:
 *  = поля
 *  = методи
 *  = властивості - нові елементи платформи
 *  = конструктори
 *  = вкладені (nested) типи
 */
